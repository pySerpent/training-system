class HelpView(ctk.CTkFrame):
    """Краткое руководство пользователя."""

    def __init__(self, master, app):
        super().__init__(master, fg_color="transparent")
        PageHeader(self, "Справка по системе", f"{config.APP_TITLE}, версия {config.APP_VERSION}").pack(anchor="w")
        box = ctk.CTkScrollableFrame(self)
        box.pack(fill="both", expand=True, pady=10)
        for title, text in SECTIONS:
            ctk.CTkLabel(box, text=title, font=("Segoe UI", 15, "bold")).pack(anchor="w", padx=14, pady=(12, 2))
            ctk.CTkLabel(box, text=text, font=FONT, wraplength=900,
                         justify="left").pack(anchor="w", padx=14)
        author = ctk.CTkFrame(self)
        author.pack(fill="x")
        ctk.CTkLabel(author, text=f"Разработчик: {config.AUTHOR_NAME}", font=("Segoe UI", 14, "bold")
                     ).pack(anchor="w", padx=14, pady=(10, 0))
        ctk.CTkLabel(author, text=f"Вы вошли как {app.user.login} ({app.user.role_title})",
                     font=FONT).pack(anchor="w", padx=14, pady=(0, 10))
